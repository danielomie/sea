# Turn Sea sources into a C header: one byte array per file and a table
# { name, src } named TABLE. An argument is name=file, or a file whose
# basename (without .sea) is the name.
#   sh tools/embed.sh SEA_TOOLS tools/fmt.sea tools/doc.sea > gen/sea_tools.h
#   sh tools/embed.sh SEA_MODULES sea/test=libs/test/test.sea > gen/sea_modules.h
set -e
table=$1
shift
echo "/* Generated by tools/embed.sh: do not edit. */"
i=0
for a in "$@"; do
    f=${a#*=}
    echo "static const char ${table}_$i[] = {"
    od -An -v -tx1 "$f" | sed 's/\([0-9a-f][0-9a-f]\)/0x\1,/g'
    echo "0x00 };"
    i=$((i + 1))
done
echo "static const struct { const char *name; const char *src; } $table[] = {"
i=0
for a in "$@"; do
    case $a in
        *=*) name=${a%%=*} ;;
        *) name=$(basename "$a" .sea) ;;
    esac
    echo "    { \"$name\", ${table}_$i },"
    i=$((i + 1))
done
echo "    { 0, 0 }"
echo "};"
