#!/bin/sh
# Turn the tool scripts (tools/*.sea) into a C header: one byte array per
# script and the SEA_TOOLS table that sea_main.c dispatches `sea <tool>` on.
# Usage: sh tools/embed.sh tools/fmt.sea tools/doc.sea > gen/sea_tools.h
set -e
echo "/* Generated by tools/embed.sh from the scripts in tools/: do not edit. */"
for f in "$@"; do
    name=$(basename "$f" .sea)
    echo "static const char SEA_TOOL_$name[] = {"
    od -An -v -tx1 "$f" | sed 's/\([0-9a-f][0-9a-f]\)/0x\1,/g'
    echo "0x00 };"
done
echo "static const struct { const char *name; const char *src; } SEA_TOOLS[] = {"
for f in "$@"; do
    name=$(basename "$f" .sea)
    echo "    { \"$name\", SEA_TOOL_$name },"
done
echo "    { 0, 0 }"
echo "};"
